def group_description(group: str) -> str:
    """这一组的说明。分组名从 `GROUPS` 取，别在界面层写中文字面量。"""
    try:
        return GROUP_DESCRIPTIONS[group]
    except KeyError as error:
        raise ValueError(f"未知分组：{group}") from error

