"""活动页左列：把「更多精彩活动」找出来的**双向扫描**参数。

## 为什么是双向（用户 2026-10-18 的原话）

> 「这个活动我点进去，它可能在任何位置都有可能，有可能这个页面还没有这个网页活动呢，
> 可能还要上滑下滑，对不对？这种情况下要怎么样才能稳定呢」

这一句把旧方案判死了：旧方案是「那一行大概在这儿 → 把搜索区域放大一点兜住它」。
可是**位置是二维的、没有上界的**，区域是固定的 ⇒ 每漂一次就得再放大一次，
而永远不知道自己放够了没有。三次漂移史就是三次补丁：

    10-06  y=425（正常）
    10-07  y=460 -> 686（被上方活动挤下去）
    10-18  y=258（列表往上滚，顶到上面去）

⇒ 结论：**位置不能当判据，只能当"扫描的起点"**。所以这里改成：

1. **判页**交给页面骨架（``activity_page_shell``），与列表滚动彻底无关；
2. **找入口**交给扫描：先在当前帧找，找不到就滑一屏再找，**滑到画面不动 = 到头了**
   就换反方向继续；两个方向都到头仍然没有 ⇒ 才收手。

## ⚠️ 方向写错了会怎样

**不会错，只会多滑几下。** 这正是这套设计的意义：方向不再是正确性前提。
如果 ``ACTIVITY_SCROLL_*`` 的物理方向猜反了（往「尾部」滑而以为在「回顶」），
那第 1 阶段会滑到尾部边界、画面不动 ⇒ 自动换反方向 ⇒ 照样扫完全表，
代价是多用掉 ``ACTIVITY_SCROLL_LIMIT_PER_DIRECTION`` 次滑动。

（2026-10-18 记：``shop_refresh`` 的注释说「往下拖＝回到顶部」，所以
``ACTIVITY_SCROLL_START_Y``（小）→ ``ACTIVITY_SCROLL_END_Y``（大）＝回顶。
这条物理常识**没有**在真机上单独验证过；上面那段保证它猜错也不影响正确性。）
"""

from __future__ import annotations

# 「更多精彩活动」在左列里的**行高**（实测 2026-10-06 / 10-07 两帧：行块高 74~84）。
ACTIVITY_ROW_HEIGHT = 84

# 一次滑多少像素。
#
# 取「接近 5 行」而不是一整屏：**步长必须小于搜索带的高度**，否则某一行可能
# 正好从带子上沿滑过去、两次取帧都没罩住（这就是「漏行」）。
# 搜索带是 ``ACTIVITY_COLUMN_Y1 - ACTIVITY_COLUMN_Y0`` = 940px，步长 400 还有
# 一倍多的重叠，怎么滑都漏不掉。
ACTIVITY_SCROLL_STEP = 400

# 滚动起点的 x。用户 2026-10-08 拍板：「左列文字上（约 x=90）」。
#
# ⚠️ 与竖屏信息流不同：这一列**没有**一条干净的白边可躲 —— 左列整条是橙/白底
# 加装饰（实测 x=15/30/60/90/120 的彩色占比都在 0.17~0.24，没有任何一列干净）。
# 所以这里的选择不是「躲到干净的地方」，而是「退化成点击时点到什么」：
# x=90 正落在**活动名那一行文字**上，点中的效果只是切换选中项 —— 无害且可恢复，
# 比点到右侧插图/横幅（那些才会打开别的东西）安全得多。
ACTIVITY_SCROLL_X = 90

# ---- 两个方向的手势 ----
#
# 「更多精彩活动」是列表**头部的元入口**（它排在所有具体活动之前），所以
# **回顶那一下**是主方向：手指往下拖 ⇒ 内容下移 ⇒ 露出上面的行。
ACTIVITY_SCROLL_START_Y = 500
ACTIVITY_SCROLL_END_Y = ACTIVITY_SCROLL_START_Y + ACTIVITY_SCROLL_STEP  # 900
#
# 反方向（往列表尾部扫）。到顶了还没有，才用这一对。
ACTIVITY_SCROLL_TAIL_START_Y = 900
ACTIVITY_SCROLL_TAIL_END_Y = ACTIVITY_SCROLL_TAIL_START_Y - ACTIVITY_SCROLL_STEP

# 每个方向最多滑几次。两个方向合计 ≤ 2 × 3 = 6 次，最坏 6 × 400 = 2400px，
# 够覆盖一整屏列表（10~12 行 ≈ 1000px）还有余量。
#
# ⚠️ 上限必须是「每个方向」而不是「总共」：写在总共那就会让第 2 个方向
# 分不到额度，等于还是单向扫描。
ACTIVITY_SCROLL_LIMIT_PER_DIRECTION = 3

# 滚动动作持续多久（和 ``FEED_TASK_SCROLL_MS`` 同一量级）。
ACTIVITY_SCROLL_MS = 400

# 左列区域。x 20~420 = 列表文字那一列；y 180~1120 = 列表可见区
# （上面 0~180 是「‹ 活动」横幅，下面 1120 之后是屏幕边缘）。
ACTIVITY_COLUMN_X0 = 20
ACTIVITY_COLUMN_X1 = 420
ACTIVITY_COLUMN_Y0 = 180
ACTIVITY_COLUMN_Y1 = 1120
