"""活动页左列：找「更多精彩活动」找不到时，就往上滚一屏再找。

背景（用户 2026-10-08 提的）：
游戏**记得**上一次在活动页点的是哪个活动 ⇒ 下次进来还停在那一个。
如果上次点的活动在列表很下面，「更多精彩活动」就被挤到屏幕外 ——
那时不管是判页（``activity_menu`` / ``activity_web_promo``）还是点击目标都找不到它，
导航卡在第一步。

所以这里给一个兜底：**找不着就滚一屏，滚完再找**，最多滚 3 次；滚满还没出现
就说明不是「滚过头」而是活动页真改版了，报错收手（绝不蒙着点）。
"""

from __future__ import annotations

# 「更多精彩活动」在左列里的**行高**（实测 2026-10-06 / 10-07 两帧：行块高 74~84）。
ACTIVITY_ROW_HEIGHT = 84

# 一次滚多少像素。
#
# 取「一行半」而不是一整屏：左列一屏能看到 8~10 行，滚一行半能保证**任何一行都
# 不会因为跨两次滚动而被跳过**（滚一屏则可能正好把那一行从视野上沿滑过去，
# 而模板搜索带 y 300~1150 又够不到）。代价是可能要滚两次 —— 上限 3 次够用。
ACTIVITY_SCROLL_STEP = 126

# 滚动起点的 x。用户 2026-10-08 拍板：「左列文字上（约 x=90）」。
#
# ⚠️ 与竖屏信息流不同：这一列**没有**一条干净的白边可躲 —— 左列整条是橙/白底
# 加装饰（实测 x=15/30/60/90/120 的彩色占比都在 0.17~0.24，没有任何一列干净）。
# 所以这里的选择不是「躲到干净的地方」，而是「退化成点击时点到什么」：
# x=90 正落在**活动名那一行文字**上，点中的效果只是切换选中项 —— 无害且可恢复，
# 比点到右侧插图/横幅（那些才会打开别的东西）安全得多。
ACTIVITY_SCROLL_X = 90

# 滚动起止 y。⚠️ 与 ``FEED_*`` 同一条纪律：**不要在页面正中**，这里 x 已经不是
# 中线了；y 取左列可见区的中下段。
ACTIVITY_SCROLL_START_Y = 900
ACTIVITY_SCROLL_END_Y = ACTIVITY_SCROLL_START_Y - ACTIVITY_SCROLL_STEP

# 滚动动作持续多久（和 ``FEED_TASK_SCROLL_MS`` 同一量级）。
ACTIVITY_SCROLL_MS = 400

# 左列区域（判「还有没有下一行」用）：x 20~420。
ACTIVITY_COLUMN_X0 = 20
ACTIVITY_COLUMN_X1 = 420
